export function getCategoriesByServant(servant: "pam" | "kongo"): VideoCategory[] {
  const vids = servant === "pam" ? PAM_VIDEOS : KONGO_VIDEOS;
  const catsMap = new Map<string, VideoItem[]>();
  for (const v of vids) {
    if (!catsMap.has(v.category)) catsMap.set(v.category, []);
    catsMap.get(v.category)!.push(v);
  }
  return Array.from(catsMap.entries()).map(([name, vs], i) => ({
    id: `${servant}-cat-${i}`,
    name,
    description: {"Lives & Directs":"Diffusions en direct de Pam — enseignements, prières et partages en temps réel avec la communauté.","Prière & Délivrance":"Sessions de prière fervente, délivrance spirituelle et intercession pour les âmes et les nations.","Enseignements & Prédications":"Enseignements bibliques approfondis et prédications sur les fondements de la foi en Yeshua HaMashiach.","Témoignages & Visions":"Témoignages authentiques, visions célestes et révélations reçues du Seigneur par Pam.","Fêtes & Shabbat":"Enseignements sur les fêtes de l'Éternel, la sanctification du Shabbat et le calendrier biblique.","Paroles & Exhortations":"Paroles d'exhortation, encouragements et instructions prophétiques pour le peuple de Dieu."}[name] || "",
    servant,
    videos: vs,
  }));
}

export function getAllVideos(): VideoItem[] {
  return [...PAM_VIDEOS, ...KONGO_VIDEOS];
}

export function getVideoById(id: string): VideoItem | undefined {
  return getAllVideos().find((v) => v.id === id);
}
